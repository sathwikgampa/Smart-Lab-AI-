def _sqlite_copy_of(tmp_path):
    """A SQLite database with the app schema, seed data, user data and a self-referencing comment."""
    from app import create_app
    from app.config import TestConfig

    create_app(TestConfig, DATA_DIR=tmp_path, DATABASE_PATH=tmp_path / "src.db", UPLOAD_DIR=tmp_path / "u",
               INDEX_DIR=tmp_path / "i")
    src = sqlite3.connect(tmp_path / "src.db")
    src.execute("INSERT INTO audit_log (action, entity_type, entity_id, summary) VALUES ('edit', 'settings', NULL, 'x')")
    # A reply stored before its parent (higher parent id) exercises the two-pass self-reference copy.
    src.execute("INSERT INTO comments (id, entity_type, entity_id, parent_id, body) VALUES (50, 'experiment', 1, 60, 'child')")
    src.execute("INSERT INTO comments (id, entity_type, entity_id, parent_id, body) VALUES (60, 'experiment', 1, NULL, 'parent')")
    src.commit()
    src.close()
    ro = sqlite3.connect((tmp_path / "src.db").resolve().as_uri() + "?mode=ro", uri=True)
    ro.row_factory = sqlite3.Row
    return ro


def test_migrate_sqlite_to_postgres(tmp_path):
    src = _sqlite_copy_of(tmp_path)
    expected = {t: src.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0] for t in TABLES}
    with postgres_test_schema() as url:
        dst = connect(url)
        try:
            # Dry run writes nothing.
            migrate(src, dst, dry_run=True, log=lambda *_: None)
            assert all(dst.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0] == 0 for t in TABLES)

            copied = migrate(src, dst, log=lambda *_: None)
            assert copied == expected
            for table in TABLES:
                assert dst.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0] == expected[table]
            # Primary keys, foreign keys, NULLs and timestamps preserved.
            for table in ("documents", "chunks", "comments", "audit_log", "chat_messages"):
                src_rows = [tuple(r) for r in src.execute(f"SELECT * FROM {table} ORDER BY id")]
                dst_rows = [tuple(r) for r in dst.execute(f"SELECT * FROM {table} ORDER BY id")]
                assert src_rows == dst_rows, table
            assert dst.execute("SELECT parent_id FROM comments WHERE id = 50").fetchone()[0] == 60
            # New rows continue after the copied ids.
            max_id = dst.execute("SELECT MAX(id) FROM comments").fetchone()[0]
            new_id = dst.execute("INSERT INTO comments (entity_type, entity_id, body) VALUES ('experiment', 1, 'new')").lastrowid
            assert new_id == max_id + 1
            dst.rollback()

            # A second run refuses to touch a non-empty database.
            with pytest.raises(MigrationError, match="already contains data"):
                migrate(src, dst, log=lambda *_: None)
            assert dst.execute("SELECT COUNT(*) FROM documents").fetchone()[0] == expected["documents"]
        finally:
            dst.close()
            src.close()
