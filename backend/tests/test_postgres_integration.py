TIMESTAMP = re.compile(r"^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$")


def test_app_runs_on_postgres(app, client, conn):
    assert is_postgres(conn) and app.config["DATABASE_ENGINE"] == "postgresql"
    assert client.get("/api/health").get_json()["database"] == "postgresql"


def test_generated_ids_and_identity_columns(conn):
    first = conn.execute("INSERT INTO profiles (name, role) VALUES (?, ?)", ("A", "QA")).lastrowid
    second = conn.execute("INSERT INTO profiles (name, role) VALUES (?, ?)", ("B", "QA")).lastrowid
    conn.commit()
    assert isinstance(first, int) and second == first + 1
    assert conn.execute("SELECT name FROM profiles WHERE id = ?", (second,)).fetchone()["name"] == "B"


def test_timestamps_keep_sqlite_text_format(client):
    exp = client.post("/api/experiments", json={"title": "Format check", "steps": ["one"]}).get_json()
    assert TIMESTAMP.match(exp["created_at"]) and TIMESTAMP.match(exp["updated_at"])


def test_numeric_aggregates_are_json_numbers(client):
    profiles = client.get("/api/profiles").get_json()
    assert any(isinstance(p["avg_progress"], float) for p in profiles)
    assert all(isinstance(p["experiment_count"], int) for p in profiles)


def test_real_columns_keep_double_precision(conn):
    rid = conn.execute("INSERT INTO reagents (name, quantity, unit) VALUES (?, ?, ?)",
                       ("Precise", 0.123456789012, "mL")).lastrowid
    assert conn.execute("SELECT quantity FROM reagents WHERE id = ?", (rid,)).fetchone()[0] == 0.123456789012
    conn.rollback()


def test_like_is_case_insensitive_and_percent_literals_work(conn):
    lower = conn.execute("SELECT COUNT(*) FROM documents WHERE title LIKE 'sop-cen%'").fetchone()[0]
    with_param = conn.execute("SELECT COUNT(*) FROM documents WHERE title LIKE 'sop-%' AND id > ?", (0,)).fetchone()[0]
    assert lower == 1 and with_param >= 4


def test_failed_statement_rolls_back_and_connection_recovers(conn):
    conn.execute("INSERT INTO profiles (name, role) VALUES ('Pending', 'QA')")
    with pytest.raises(Exception):
        conn.execute("INSERT INTO chunks (document_id, page, chunk_index, text) VALUES (?, ?, ?, ?)",
                     (999999, 1, 0, "orphan"))  # foreign-key violation
    conn.rollback()
    assert conn.execute("SELECT COUNT(*) FROM profiles WHERE name = 'Pending'").fetchone()[0] == 0


def test_request_errors_do_not_poison_pooled_connections(app, client):
    # An unexpected database error inside a request leaves an aborted transaction; teardown must roll it back.
    @app.get("/api/_boom")
    def boom():
        from app.db import get_db
        get_db().execute("SELECT * FROM no_such_table")

    assert client.get("/api/_boom").status_code == 500
    for _ in range(app.config["DB_POOL_MAX"] + 1):
        assert client.get("/api/reagents").status_code == 200


def test_upsert_settings(client):
    assert client.put("/api/settings", json={"institution_name": "One"}).status_code == 200
    body = client.put("/api/settings", json={"institution_name": "Two"}).get_json()
    assert body["editable"]["institution_name"] == "Two"


def test_init_schema_adds_missing_columns_without_data_loss():
    with postgres_test_schema() as url:
        conn = connect(url)
        try:
            conn.executescript("CREATE TABLE documents (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                               "stored_name TEXT, original_name TEXT, title TEXT, doc_type TEXT, page_count INTEGER, "
                               "chunk_count INTEGER, size_bytes INTEGER, sha256 TEXT UNIQUE, status TEXT, "
                               "uploaded_at TEXT); INSERT INTO documents (title, sha256) VALUES ('Legacy', 'abc');")
            conn.commit()
            init_schema(conn)
            init_schema(conn)
            row = conn.execute("SELECT title, approval_status, category FROM documents").fetchone()
            assert tuple(row) == ("Legacy", "unreviewed", "General")
        finally:
            conn.close()


